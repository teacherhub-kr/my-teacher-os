const assert=require("assert");
const fs=require("fs"),path=require("path");
const Core=require("../music-summary-core-v54.js");
const headers=["학년/반","학년","1차 미채점","2차 미채점","3차 미채점","4차 미채점","현황","연동 상태","참조 평가일","일정표 단계","점검 알림"];
const rows=[headers];
for(let i=1;i<=9;i++)rows.push(["2-"+i,"2","0","1","20","20","2차 진행","자동 연동","","2차",'점검, 보충']);
for(let i=4;i<=9;i++)rows.push(["3-"+i,"3","0","0","0","1","4차 진행","1·2차 PDF(1학기)","","3차","마감 긴급"]);
const quote=v=>'"'+String(v).replace(/"/g,'""')+'"';
const csv=['"2026 음악 2학기 수행평가"','"미채점 0명은 채점완료만 의미"'].concat(rows.map(r=>r.map(quote).join(","))).join("\r\n");
const parsed=Core.parseDelimited("\uFEFF"+csv);
assert.equal(parsed.classes.length,15);
assert.equal(parsed.missingTotal,9*(1+20+20)+6);
assert.equal(parsed.urgentClasses,6);
assert.equal(parsed.classes[0].id,"2-1");
assert.equal(parsed.classes.at(-1).id,"3-9");
assert.equal(Core.parseDelimited(rows.map(r=>r.join("\t")).join("\n")).classes.length,15);
assert.equal(Core.parseDelimited(rows.map(r=>r.join(",")).join("\n")).classes.length,15);
assert.throws(()=>Core.parseDelimited(csv.replace('"2-3"','"2-2"')),/중복/);
assert.throws(()=>Core.parseDelimited(csv.replace('"20"','"=20+0"')),/미채점 수치/);
assert.throws(()=>Core.parseDelimited(csv.replace('"3-9"','"4-9"')),/학급 코드/);
assert.throws(()=>Core.parseDelimited(csv.replace('"1"','"47"')),/미채점 수치/);
assert.throws(()=>Core.parseDelimited("x,y\n1,2"),/제목/);
assert.throws(()=>Core.parseDelimited('"unclosed'),/따옴표/);
const ui=fs.readFileSync(path.join(__dirname,"../music-summary-v54.js"),"utf8");
const css=fs.readFileSync(path.join(__dirname,"../music-summary-v54.css"),"utf8");
assert(ui.includes('Core.parseDelimited(input)')&&ui.includes('file.text()'),"CSV browser import must actually work");
assert(!ui.includes('globalThis.XLSX'),"unloaded XLSX must not be advertised");
assert(ui.includes('CSV 파일로 임시 조회')&&!ui.includes('엑셀 파일로 임시 조회'));
assert(ui.includes('1차(1학기 참고)')&&ui.includes('3차(2학기)'));
assert(ui.includes('lastGoodReadAt')&&ui.includes('fetchGeneration')&&ui.includes('lastAttemptAt'),"stale/in-flight protection missing");
assert(css.includes('.music54-table'));
console.log("v55 CSV/TSV local import, academic semester, no fake XLSX and refresh guards PASS");